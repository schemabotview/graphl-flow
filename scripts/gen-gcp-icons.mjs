// Writes src/gcp-icons.ts: the Google Cloud product icons a scene uses, copied from the pinned
// @iconify-json/gcp (Google Cloud Icons, Apache-2.0). The package is one 160 KB JSON that cannot
// tree-shake, so only these keys ship. Add a key here, then `node scripts/gen-gcp-icons.mjs`.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const KEYS = {
  gcs: 'cloud-storage', bigquery: 'bigquery', pubsub: 'pubsub', dataflow: 'dataflow', dataproc: 'dataproc',
  composer: 'cloud-composer', cloudkms: 'key-management-service', secretmanager: 'secret-manager',
  gcpiam: 'identity-and-access-management', dataplex: 'dataplex', dlp: 'data-loss-prevention-api',
  cloudlogging: 'cloud-logging', cloudmonitoring: 'cloud-monitoring', cloudbuild: 'cloud-build',
  gcpproject: 'project', gcpbilling: 'billing',
}

const require = createRequire(import.meta.url)
const pkg = require('@iconify-json/gcp/package.json')
const { icons, width = 16, height = 16 } = JSON.parse(readFileSync(require.resolve('@iconify-json/gcp/icons.json'), 'utf8'))
const out = Object.entries(KEYS).map(([key, name]) => {
  const icon = icons[name]
  if (!icon) throw new Error(`@iconify-json/gcp has no icon "${name}"`)
  if ((icon.width ?? width) !== 24 || (icon.height ?? height) !== 24) throw new Error(`"${name}" is not 24×24`)
  return `  ${key}: { title: ${JSON.stringify(name)}, body: ${JSON.stringify(icon.body)} },`
})
writeFileSync('src/gcp-icons.ts', `// GENERATED by scripts/gen-gcp-icons.mjs from @iconify-json/gcp ${pkg.version} — do not edit.
// Google Cloud Icons © Google LLC, Apache-2.0 (https://www.apache.org/licenses/LICENSE-2.0).
/** Google Cloud product icons in their own colours: 24×24 SVG bodies, keyed as scenes name them. */
export const GCP: Record<string, { title: string; body: string }> = {
${out.join('\n')}
}
`)
console.log(`src/gcp-icons.ts: ${out.length} icons from @iconify-json/gcp ${pkg.version}`)
